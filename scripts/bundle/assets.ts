// The kit's LIBRARY.md and CREDITS.md (scripts/bundle.mjs loads this module through tsx):
// what the built-in model and texture libraries hold, and where everything the kit carries came
// from. Generated from the same data `npm run model -- find` and `npm run model -- credits` read:
// the defs themselves and each one's `source`.
import { buildModel, MODEL_LIBRARY, OWN_LICENCE } from '../../src/engine/model';
import { creditEntries, creditLine } from '../../src/engine/model/packs/credits';
import { TEXTURE_LIBRARY } from '../../src/engine/texture';

const fmt = (v: number) => `${+v.toFixed(2)}`;
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ');

/** LIBRARY.md: every built-in model and texture, one table row each. */
export function libraryMarkdown(version: string): string {
  const models = MODEL_LIBRARY.all().map((d) => {
    const size = buildModel(d).bounds.size.map(fmt).join(' × ');
    const params = Object.entries(d.params ?? {}).map(([k, [v, lo, hi]]) => `${k} ${v} (${lo}–${hi})`).join(', ');
    const slots = Object.entries(d.palette).map(([s, c]) => `${s} ${c}`).join(', ');
    return `| \`${d.id}\` | ${size} | ${params} | ${slots} | ${cell(d.about)} |`;
  });
  const textures = TEXTURE_LIBRARY.all().map((d) => {
    const kind = [d.tile ? 'tiles' : '', d.frames && d.frames > 1 ? `${d.frames} frames` : ''].filter(Boolean).join(', ');
    const slots = Object.entries(d.palette).map(([s, c]) => `${s} ${c}`).join(', ');
    return `| \`${d.id}\` | ${d.size[0]} × ${d.size[1]}${kind ? `, ${kind}` : ''} | ${slots} | ${cell(d.about)} |`;
  });
  return `${[
    `# The library (Pixel Engine ${version})`,
    '',
    `Every built-in model (\`MODEL_LIBRARY\`, ${models.length}) and texture (\`TEXTURE_LIBRARY\`, ${textures.length}), generated from the defs. Search it; don't read it whole. ` +
      'Place one with `buildModel(id, { params, palette })`, `use` it inside your own models, and look at it first: `node check.mjs --sheets <id>` (ASSETS.md).',
    '',
    '## Models',
    '',
    '| id | size (m, w × h × d) | params: default (min–max) | palette slots | about |',
    '| --- | --- | --- | --- | --- |',
    ...models,
    '',
    '## Textures',
    '',
    '| id | texels | palette slots | about |',
    '| --- | --- | --- | --- |',
    ...textures,
  ].join('\n')}\n`;
}

/** A bundled package: its name, version, licence and url, and its licence file's text. */
export interface CodeCredit {
  readonly name: string;
  readonly version: string;
  readonly licence: string;
  readonly url: string;
  readonly text: string;
}

/**
 * Palettes the engine carries that someone else made (src/engine/palette.ts, the filters in
 * src/engine/render/filters.ts): credited as their sources name them, with no licence claimed.
 */
const PALETTE_CREDITS = [
  { name: 'Sweetie 16', by: 'GrafxKid', where: "the engine's 16 colours (`PALETTE`) and the `sweetie16` filter" },
  { name: 'PICO-8', by: 'Lexaloffle Games (the PICO-8 fantasy console)', where: 'the `pico8` filter' },
];

/**
 * CREDITS.md: the models and textures (`creditEntries`, as `model -- credits`), the built-in GLBs,
 * the palettes and the bundled code with its licence texts. The kit ships no packs today; when it
 * does, their models (public/packs/*.json, each with its `source`) join `creditEntries` here, as
 * they do in `model -- credits`.
 */
export function creditsMarkdown(o: { version: string; builtins: readonly string[]; code: readonly CodeCredit[] }): string {
  const models = MODEL_LIBRARY.all();
  const textures = TEXTURE_LIBRARY.all();
  const own = (defs: readonly { source?: { licence: string } }[]) => defs.filter((d) => !d.source || d.source.licence === OWN_LICENCE).length;
  const imported = creditEntries(models, textures).filter((e) => e.licence !== OWN_LICENCE);
  return `${[
    `# Credits (Pixel Engine ${o.version})`,
    '',
    'What this kit carries and where it came from, generated by `npm run bundle` from each built-in model\'s and texture\'s `source` ' +
      '(the data the engine repository\'s `npm run model -- credits` reads) and from the bundled packages\' own licence files. ' +
      'Ship this file with a game built on the kit.',
    '',
    '## Models and textures',
    '',
    `- **The engine's own work**, made in its repository: ${own(models)} of the ${models.length} library models (\`MODEL_LIBRARY\`), ` +
      `${own(textures)} of the ${textures.length} textures (\`TEXTURE_LIBRARY\`) and the built-in models (${o.builtins.map((b) => `\`${b}\``).join(', ')}). Nothing to credit.`,
    ...(imported.length ? imported.map(creditLine) : ['- **Imported from anyone else:** nothing.']),
    "- **Your own imports** carry a `source` too (url, licence, author): credit them as their licence asks. A pack loaded with `loadPack` carries its models' `source`s.",
    '',
    '## Palettes',
    '',
    ...PALETTE_CREDITS.map((p) => `- **${p.name}** by ${p.by}: ${p.where}.`),
    '',
    '## Code',
    '',
    ...o.code.map((c) => `- **${c.name}** ${c.version}, ${c.licence}: ${c.url}. Its licence follows.`),
    ...o.code.flatMap((c) => ['', `### ${c.name} licence`, '', '```text', c.text.trimEnd(), '```']),
  ].join('\n')}\n`;
}
