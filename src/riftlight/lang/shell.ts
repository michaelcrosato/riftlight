/** Every shell line (a function: the look studio's and the sliders' come from registries). */
export function SHELL(): LineArea {
  const areas = [KEYS, MENUS, PLAY, DEV, TUNED, look()];
  return {
    lines: Object.assign({}, ...areas.map((a) => a.lines)),
    notes: Object.assign({}, ...areas.map((a) => a.notes ?? {})),
    max: Object.assign({}, ...areas.map((a) => a.max ?? {})),
  };
}
